// Who is calling relo: the one place that tells caller types apart (STATE-SPEC 4.1 and 11.1a).
// Commands receive the typed caller (dependencies.caller) and branch on `caller.type`; they never read
// harness variables themselves. `relo hook` and the agent-session caller share sessionKey(), so the id
// the agent's shell sees (CLAUDE_CODE_SESSION_ID) and the hook's stdin `session_id` give one key.
import { createHash } from "node:crypto";

export const CALLER_TYPES = Object.freeze({ AGENT_SESSION: "agent_session", SCRIPT: "script", UNIDENTIFIED: "unidentified" });

/**
 * Harness session ids, as the harness exposes them to its agent's shell. Hooks get the same id as
 * `session_id` on stdin (Claude Code: documented; Codex: per its maintainers). No other harness is
 * listed because none could be confirmed from official documentation or source (Gemini CLI, Cursor
 * and OpenCode expose no id to the shell): they are unidentified.
 */
export const HARNESS_SESSION_VARIABLES = Object.freeze([["claude-code", "CLAUDE_CODE_SESSION_ID"], ["codex", "CODEX_THREAD_ID"]]);

/**
 * Set only by `relo mcp` for the commands it runs: one agent session per MCP connection, generated by
 * Relo's own server. A harness or the owner never sets it.
 */
export const MCP_SESSION_VARIABLE = "RELO_MCP_SESSION";

const text = (value) => (typeof value === "string" && value.trim() ? value.trim() : undefined);

/**
 * The calling agent harness, recognized from its environment. Only markers confirmed from the
 * harness's own source or documentation are listed; any other harness sets RELO_SOURCE.
 *  - Claude Code: CLAUDECODE=1 and CLAUDE_CODE_ENTRYPOINT (Claude Code docs, environment variables).
 *  - Codex: CODEX_* variables such as CODEX_THREAD_ID, CODEX_CI (Codex CLI); CODEX_HOME is only config.
 *  - OpenCode: OPENCODE=1 (set in OpenCode's shell tool environment).
 *  - Gemini CLI: GEMINI_CLI=1 (google-gemini/gemini-cli, packages/core/src/services/shellExecutionService.ts,
 *    GEMINI_CLI_IDENTIFICATION_ENV_VAR_VALUE, set for every shell command the agent runs).
 *  - Cursor agent (CLI and IDE terminals): CURSOR_AGENT (Cursor staff confirm the CLI exports CURSOR_AGENT=1
 *    to agent shell commands, forum.cursor.com "Cursor CLI is not setting CURSOR_AGENT=1 ..."; undocumented).
 */
export function detectAgent(env = process.env) {
  if (env.CLAUDECODE === "1" || text(env.CLAUDE_CODE_ENTRYPOINT)) return "Claude Code";
  if (Object.keys(env).some((key) => /^CODEX_(?!HOME$)/u.test(key))) return "Codex";
  if (env.OPENCODE === "1") return "OpenCode";
  if (env.GEMINI_CLI === "1") return "Gemini CLI";
  if (text(env.CURSOR_AGENT)) return "Cursor";
  return undefined;
}

/** A usable session id: a non-blank string of at most 500 characters, trimmed. */
export function sessionId(value) {
  const id = typeof value === "string" ? value.trim() : "";
  return id && id.length <= 500 ? id : undefined;
}

/** THE session key, for relo commands and `relo hook` alike: sha256 of "harness:id", base64url. */
export function sessionKey({ harness, id }) {
  return createHash("sha256").update(`${harness}:${id}`).digest("base64url");
}

const agentSessionCaller = (harness, id) => ({ type: CALLER_TYPES.AGENT_SESSION, harness, sessionId: id, sessionKey: sessionKey({ harness, id }) });

/**
 * The typed caller, from the environment only (never the directory, terminal or parent process):
 *  - agent_session {harness, sessionId, sessionKey}: exactly one harness session id, or Relo's own MCP
 *    connection (harness "mcp");
 *  - unidentified {reason, agent?}: nested harnesses (more than one harness id), or a detected harness that
 *    exposes no id. No shared session state; RELO_SESSION is ignored (it could name another session);
 *  - script {producerKey?, session?}: no harness. producerKey is --name, else RELO_SESSION; `session` is the
 *    RELO_SESSION id (a script's stable card). The owner's shell is a script without either.
 * `name` is the command's --name, if any; it never changes the type.
 */
export function detectCaller(env = process.env, { name } = {}) {
  const ids = HARNESS_SESSION_VARIABLES
    .map(([harness, variable]) => ({ harness, id: sessionId(env[variable]) }))
    .filter((found) => found.id !== undefined);
  if (ids.length > 1) return { type: CALLER_TYPES.UNIDENTIFIED, reason: "nested_harnesses" };
  if (ids.length === 1) return agentSessionCaller(ids[0].harness, ids[0].id);
  const agent = detectAgent(env);
  const session = agent === undefined ? sessionId(env.RELO_SESSION) : undefined;
  const mcp = sessionId(env[MCP_SESSION_VARIABLE]);
  // An owner who pins RELO_SESSION for an MCP server outside any harness keeps that stable key.
  if (mcp !== undefined && session === undefined) return agentSessionCaller("mcp", mcp);
  if (agent !== undefined) return { type: CALLER_TYPES.UNIDENTIFIED, reason: "no_session_id", agent };
  const producerKey = sessionId(name) ?? session;
  return { type: CALLER_TYPES.SCRIPT, ...(producerKey === undefined ? {} : { producerKey }), ...(session === undefined ? {} : { session }) };
}

/**
 * The stable owner of the caller's own card: an agent session, or a script's RELO_SESSION. Undefined for an
 * unidentified caller or a keyless script, whose card is named by source › project › topic.
 */
export function cardOwner(caller) {
  if (caller?.type === CALLER_TYPES.AGENT_SESSION) return { label: caller.harness, id: caller.sessionId };
  if (caller?.type === CALLER_TYPES.SCRIPT && caller.session !== undefined) return { label: "relo", id: caller.session };
  return undefined;
}

/** An agent's shell tool kills long commands: any agent or unidentified harness caller, or a script with RELO_SESSION. */
export function waitsShort(caller) {
  return caller !== undefined && (caller.type !== CALLER_TYPES.SCRIPT || caller.session !== undefined);
}

/** Which producer module serves this caller: "agent" (agent sessions and unidentified callers) or "script". */
export function surfaceFor(caller) {
  return caller?.type === CALLER_TYPES.SCRIPT ? "script" : "agent";
}
