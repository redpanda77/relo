// Who is calling relo: the one place that tells caller types apart (STATE-SPEC 4.1 and 11.1a).
// Commands receive the typed caller (dependencies.caller) and branch on `caller.type`; they never read
// harness variables themselves. `relo hook` and the agent-session caller share sessionKey(), so the id
// the agent's shell sees (CLAUDE_CODE_SESSION_ID) and the hook's stdin `session_id` give one key.
import { SESSION_VARIABLES, detectHarness } from "./harness/catalog.mjs";
import { sessionId, sessionKey } from "./shared/session-key.mjs";

export const CALLER_TYPES = Object.freeze({ AGENT_SESSION: "agent_session", SCRIPT: "script", UNIDENTIFIED: "unidentified", OWNER: "owner" });

/**
 * Set only by `relo mcp` for the commands it runs: one agent session per MCP connection, generated by
 * Relo's own server. A harness or the owner never sets it.
 */
export const MCP_SESSION_VARIABLE = "RELO_MCP_SESSION";

const text = (value) => (typeof value === "string" && value.trim() ? value.trim() : undefined);

/** The calling agent harness's display name, from the markers in its shell (harness/catalog.mjs), or undefined. */
export const detectAgent = (env = process.env) => detectHarness(env)?.label;

const agentSessionCaller = (harness, id) => ({ type: CALLER_TYPES.AGENT_SESSION, harness, sessionId: id, sessionKey: sessionKey({ harness, id }) });

/**
 * The typed caller, from the environment only (never the directory, terminal or parent process):
 *  - agent_session {harness, sessionId, sessionKey}: exactly one harness session id, or Relo's own MCP
 *    connection (harness "mcp");
 *  - unidentified {reason, harness?}: nested harnesses (more than one harness id), or a detected harness that
 *    exposes no id. No shared session state; RELO_SESSION is ignored (it could name another session);
 *  - owner {via}: only `relo admin` makes one (ownerCaller); never detected here;
 *  - script {producerKey?, session?}: no harness. producerKey is --name, else RELO_SESSION; `session` is the
 *    RELO_SESSION id (a script's stable card). The owner's shell is a script without either.
 * `name` is the command's --name, if any; it never changes the type.
 */
export function detectCaller(env = process.env, { name } = {}) {
  const ids = SESSION_VARIABLES
    .map(([harness, variable]) => ({ harness, id: sessionId(env[variable]) }))
    .filter((found) => found.id !== undefined);
  if (ids.length > 1) return { type: CALLER_TYPES.UNIDENTIFIED, reason: "nested_harnesses" };
  if (ids.length === 1) return agentSessionCaller(ids[0].harness, ids[0].id);
  const harness = detectHarness(env)?.id;
  const session = harness === undefined ? sessionId(env.RELO_SESSION) : undefined;
  const mcp = sessionId(env[MCP_SESSION_VARIABLE]);
  // An owner who pins RELO_SESSION for an MCP server outside any harness keeps that stable key.
  if (mcp !== undefined && session === undefined) return agentSessionCaller("mcp", mcp);
  if (harness !== undefined) return { type: CALLER_TYPES.UNIDENTIFIED, reason: "no_session_id", harness };
  const producerKey = sessionId(name) ?? session;
  return { type: CALLER_TYPES.SCRIPT, ...(producerKey === undefined ? {} : { producerKey }), ...(session === undefined ? {} : { session }) };
}

/**
 * The stable owner of the caller's own card: an agent session, or a script's RELO_SESSION. Undefined for an
 * unidentified caller or a keyless script, whose card is named by source › project › topic.
 */
export function cardOwner(caller) {
  if (caller?.type === CALLER_TYPES.AGENT_SESSION) return { label: caller.harness, id: caller.sessionId };
  if (caller?.type === CALLER_TYPES.SCRIPT && caller.session !== undefined) return { label: "relo", id: caller.session };
  return undefined;
}

/** An agent's shell tool kills long commands: any agent or unidentified harness caller, or a script with RELO_SESSION. */
export function waitsShort(caller) {
  if (caller === undefined || caller.type === CALLER_TYPES.OWNER) return false;
  return caller.type !== CALLER_TYPES.SCRIPT || caller.session !== undefined;
}

/**
 * The owner acting through `relo admin`: never detected from the environment, only made by that command,
 * so cross-session views exist only there. `via` is who typed it (the owner's shell, or an agent the owner
 * asked for help); it never changes what the owner sees.
 */
export const ownerCaller = (via) => ({ type: CALLER_TYPES.OWNER, via });

/** Which module serves this caller: "agent" (agent sessions and unidentified callers), "script", or "owner". */
export function surfaceFor(caller) {
  if (caller?.type === CALLER_TYPES.OWNER) return "owner";
  return caller?.type === CALLER_TYPES.SCRIPT ? "script" : "agent";
}
